"""Builds the handwriting fonts used by "이름으로 만들기".

Usage: python scripts/build-fonts.py <dir with the Google Fonts ofl/ folders>
Needs fonttools and brotli (pip install fonttools brotli).

Source: https://github.com/google/fonts/tree/main/ofl (SIL Open Font License 1.1)
- Nanum fonts reserve the name "Nanum", so they are copied unmodified.
- The others have no reserved name; they are subset to ASCII + Hangul and
  saved as WOFF2 to keep the extension small.
Writes fonts/<id>.<ext>, fonts/<id>-OFL.txt and src/handwritingFonts.js
(labels, files and the characters each font covers).
"""
import json
import shutil
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1])
FONTS = [
    # id, label, source file, keep unmodified (reserved font name)
    ("nanum-pen", "나눔손글씨 펜", "nanumpenscript/NanumPenScript-Regular.ttf", True),
    ("nanum-brush", "나눔손글씨 붓", "nanumbrushscript/NanumBrushScript-Regular.ttf", True),
    ("dokdo", "동해 독도", "eastseadokdo/EastSeaDokdo-Regular.ttf", False),
    ("gaegu", "개구", "gaegu/Gaegu-Regular.ttf", False),
]
KEEP = [(0x20, 0x7E), (0xB7, 0xB7), (0x3131, 0x318E), (0xAC00, 0xD7A3)]


def ranges(codes):
    out = []
    for c in sorted(codes):
        if out and c == out[-1][1] + 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


out_dir = ROOT / "fonts"
out_dir.mkdir(exist_ok=True)
entries = []
for font_id, label, rel, unmodified in FONTS:
    src = SRC / rel
    cmap = TTFont(src).getBestCmap()
    covered = {c for c in cmap if any(a <= c <= b for a, b in KEEP)}
    if unmodified:
        dest = out_dir / f"{font_id}.ttf"
        shutil.copyfile(src, dest)
    else:
        dest = out_dir / f"{font_id}.woff2"
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.notdef_outline = True
        font = subset.load_font(str(src), options)
        sub = subset.Subsetter(options)
        sub.populate(unicodes=covered)
        sub.subset(font)
        subset.save_font(font, str(dest), options)
    shutil.copyfile(src.parent / "OFL.txt", out_dir / f"{font_id}-OFL.txt")
    entries.append({"id": font_id, "label": label, "file": f"fonts/{dest.name}", "covers": ranges(covered)})
    print(f"{dest.name}: {dest.stat().st_size // 1024} KB, {len(covered)} characters")

js = (
    "// Generated by scripts/build-fonts.py. Do not edit by hand.\n"
    "// Handwriting fonts for 이름으로 만들기 and the characters each one covers.\n"
    f"export const HANDWRITING_FONTS = {json.dumps(entries, ensure_ascii=False, separators=(',', ':'))};\n"
)
(ROOT / "src" / "handwritingFonts.js").write_text(js, encoding="utf-8", newline="\n")
